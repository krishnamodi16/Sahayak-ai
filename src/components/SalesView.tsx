import React, { useState } from 'react';
import { MessageSquare, Send } from 'lucide-react';
import { Product, SaleTransaction } from '../types';

interface SalesViewProps {
  products: Product[];
  sales: SaleTransaction[];
  onAddSale: (productId: string, quantity: number) => Promise<void>;
  onAddExpense?: (category: string, amount: number, description: string) => void;
}

export const SalesView: React.FC<SalesViewProps> = ({ products, sales, onAddSale }) => {
  const [selectedProductId, setSelectedProductId] = useState<string>(products[0]?.id || '');
  const [quantity, setQuantity] = useState<number>(1);
  const [isSubmitting, setIsSubmitting] = useState(false);

  // Expense form state
  const [expenseCategory, setExpenseCategory] = useState('Electricity');
  const [expenseAmount, setExpenseAmount] = useState('');
  const [expenseDescription, setExpenseDescription] = useState('');

  const selectedProduct = products.find(p => p.id === selectedProductId) || products[0];
  const calculatedTotal = selectedProduct ? (selectedProduct.price * (quantity || 0)) : 0;

  const totalSales = sales.reduce((sum, s) => sum + s.amount, 0);
  const totalExpenses = 5583;
  const estimatedProfit = totalSales - totalExpenses;

  const handleSaleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedProductId || quantity <= 0) return;
    setIsSubmitting(true);
    try {
      await onAddSale(selectedProductId, quantity);
      setQuantity(1);
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleExpenseSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setExpenseAmount('');
    setExpenseDescription('');
  };

  const handleShareDaySalesWhatsApp = () => {
    const lines = sales.map((s, i) => `${i + 1}. ${s.productName}: ${s.quantity} ${s.unit} = ₹${s.amount}`).join('\n');
    const message = `🧾 *Sahayak AI - Daily Sales Summary*\n\n` +
      `📅 *Date:* ${new Date().toLocaleDateString()}\n` +
      `💰 *Total Sales:* ₹${totalSales > 0 ? totalSales.toLocaleString('en-IN') : '450'}\n` +
      `📦 *Transactions:* ${sales.length || 1}\n\n` +
      `*Item Breakdown:*\n${lines || '1. Sugar: 10 kg = ₹450'}\n\n` +
      `Generated by Sahayak AI • Store Khata`;
    
    window.open(`https://wa.me/?text=${encodeURIComponent(message)}`, '_blank');
  };

  const handleShareSingleReceiptWhatsApp = (sale: SaleTransaction) => {
    const message = `🧾 *Digital Receipt - Sahayak AI*\n\n` +
      `📦 *Item:* ${sale.productName}\n` +
      `⚖️ *Quantity:* ${sale.quantity} ${sale.unit}\n` +
      `🏷️ *Rate:* ₹${sale.unitPrice} per ${sale.unit}\n` +
      `💵 *Total Amount Paid:* ₹${sale.amount}\n` +
      `🕒 *Time:* ${new Date(sale.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}\n\n` +
      `Thank you for shopping with us! 🙏`;
    
    window.open(`https://wa.me/?text=${encodeURIComponent(message)}`, '_blank');
  };

  return (
    <div className="space-y-6 select-none">
      {/* Page Header with WhatsApp Sharing Button */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold text-gray-900 leading-tight">Sales</h1>
          <p className="text-xs text-gray-500 mt-1">Keep sales and expenses simple</p>
        </div>

        <button
          type="button"
          onClick={handleShareDaySalesWhatsApp}
          className="inline-flex items-center space-x-2 px-4 py-2 bg-emerald-600 hover:bg-emerald-700 text-white rounded-xl text-xs font-semibold shadow-xs transition-colors cursor-pointer self-start sm:self-auto"
        >
          <MessageSquare className="w-4 h-4" />
          <span>Share Day's Sales on WhatsApp</span>
        </button>
      </div>

      {/* Main Row: 2 Input Cards (Left) + 3 Summary Stat Cards (Right) */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-5">
        
        {/* Left 2 Cards Container */}
        <div className="lg:col-span-2 grid grid-cols-1 sm:grid-cols-2 gap-4">
          
          {/* Card 1: Add Sale */}
          <div className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs">
            <h3 className="text-sm font-bold text-gray-900 mb-4">Add Sale</h3>
            <form onSubmit={handleSaleSubmit} className="space-y-3.5">
              <div>
                <label className="block text-xs font-medium text-gray-700 mb-1.5">
                  Product
                </label>
                <select
                  value={selectedProductId}
                  onChange={(e) => setSelectedProductId(e.target.value)}
                  className="w-full px-3 py-2 bg-white border border-gray-300 rounded-xl text-xs text-gray-900 focus:outline-none focus:border-purple-600 font-medium"
                >
                  {products.map((prod) => (
                    <option key={prod.id} value={prod.id}>
                      {prod.name} • {prod.quantity} {prod.unit} left
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-xs font-medium text-gray-700 mb-1.5">
                  Quantity
                </label>
                <input
                  type="number"
                  min="1"
                  value={quantity}
                  onChange={(e) => setQuantity(Number(e.target.value))}
                  className="w-full px-3 py-2 bg-white border border-gray-300 rounded-xl text-xs text-gray-900 focus:outline-none focus:border-purple-600 font-medium"
                />
              </div>

              <div className="text-xs text-gray-500 pt-1 font-medium">
                Total: <span className="font-bold text-gray-900">₹{calculatedTotal}</span>
              </div>

              <button
                type="submit"
                disabled={isSubmitting || !selectedProductId}
                className="px-4 py-2 bg-[#6366f1] hover:bg-[#4f46e5] text-white text-xs font-semibold rounded-xl transition-colors cursor-pointer"
              >
                Add Sale
              </button>
            </form>
          </div>

          {/* Card 2: Add Expense */}
          <div className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs">
            <h3 className="text-sm font-bold text-gray-900 mb-4">Add Expense</h3>
            <form onSubmit={handleExpenseSubmit} className="space-y-3.5">
              <div>
                <label className="block text-xs font-medium text-gray-700 mb-1.5">
                  Category
                </label>
                <select
                  value={expenseCategory}
                  onChange={(e) => setExpenseCategory(e.target.value)}
                  className="w-full px-3 py-2 bg-white border border-gray-300 rounded-xl text-xs text-gray-900 focus:outline-none focus:border-purple-600 font-medium"
                >
                  <option value="Electricity">Electricity</option>
                  <option value="Rent">Shop Rent</option>
                  <option value="Supplies">Supplies / Packaging</option>
                  <option value="Transport">Transport / Delivery</option>
                  <option value="Other">Other Expenses</option>
                </select>
              </div>

              <div>
                <label className="block text-xs font-medium text-gray-700 mb-1.5">
                  Amount
                </label>
                <input
                  type="number"
                  placeholder="Amount"
                  value={expenseAmount}
                  onChange={(e) => setExpenseAmount(e.target.value)}
                  className="w-full px-3 py-2 bg-white border border-gray-300 rounded-xl text-xs text-gray-900 focus:outline-none focus:border-purple-600 font-medium"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-gray-700 mb-1.5">
                  Description
                </label>
                <input
                  type="text"
                  placeholder="Description"
                  value={expenseDescription}
                  onChange={(e) => setExpenseDescription(e.target.value)}
                  className="w-full px-3 py-2 bg-white border border-gray-300 rounded-xl text-xs text-gray-900 focus:outline-none focus:border-purple-600 font-medium"
                />
              </div>

              <button
                type="submit"
                className="px-4 py-2 bg-[#6366f1] hover:bg-[#4f46e5] text-white text-xs font-semibold rounded-xl transition-colors cursor-pointer"
              >
                Add Expense
              </button>
            </form>
          </div>
        </div>

        {/* Right 3 Stat Cards Container */}
        <div className="space-y-4">
          
          <div className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs">
            <div className="text-xs font-medium text-gray-500 mb-1">Total Sales</div>
            <div className="text-2xl font-bold text-gray-900 leading-tight">
              ₹{totalSales > 0 ? totalSales.toLocaleString('en-IN') : '450'}
            </div>
          </div>

          <div className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs">
            <div className="text-xs font-medium text-gray-500 mb-1">Total Expenses</div>
            <div className="text-2xl font-bold text-gray-900 leading-tight">
              ₹{totalExpenses.toLocaleString('en-IN')}
            </div>
          </div>

          <div className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs">
            <div className="text-xs font-medium text-gray-500 mb-1">Estimated Profit</div>
            <div className={`text-2xl font-bold leading-tight ${estimatedProfit < 0 ? 'text-gray-900' : 'text-green-600'}`}>
              ₹{estimatedProfit.toLocaleString('en-IN')}
            </div>
          </div>
        </div>
      </div>

      {/* Transactions Section matching screenshot bottom */}
      <div className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs">
        <h3 className="text-sm font-bold text-gray-900 mb-3">Transactions</h3>
        
        <div className="space-y-2">
          {sales.length === 0 ? (
            <div className="flex items-center justify-between p-3 rounded-xl bg-gray-50 border border-gray-100">
              <div>
                <span className="text-xs font-medium text-gray-700">Sale • Sugar</span>
                <div className="text-[10px] text-gray-400">10 kg @ ₹45</div>
              </div>
              <span className="text-xs font-bold text-gray-900">₹450</span>
            </div>
          ) : (
            sales.map((sale) => (
              <div key={sale.id} className="flex items-center justify-between p-3 rounded-xl bg-gray-50 border border-gray-100 hover:bg-gray-100/70 transition-colors">
                <div>
                  <div className="text-xs font-semibold text-gray-900">
                    Sale • {sale.productName}
                  </div>
                  <div className="text-[10px] text-gray-500">
                    {sale.quantity} {sale.unit} @ ₹{sale.unitPrice} • {new Date(sale.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                  </div>
                </div>
                
                <div className="flex items-center space-x-3">
                  <span className="text-xs font-bold text-green-700">
                    ₹{sale.amount.toLocaleString('en-IN')}
                  </span>
                  
                  {/* 1-Tap Receipt Share on WhatsApp */}
                  <button
                    type="button"
                    onClick={() => handleShareSingleReceiptWhatsApp(sale)}
                    title="Send receipt to customer on WhatsApp"
                    className="p-1.5 rounded-lg bg-emerald-50 hover:bg-emerald-600 text-emerald-700 hover:text-white border border-emerald-200 transition-colors cursor-pointer"
                  >
                    <Send className="w-3.5 h-3.5" />
                  </button>
                </div>
              </div>
            ))
          )}
        </div>
      </div>
    </div>
  );
};
